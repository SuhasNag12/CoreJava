public class Car {

    private String name;
    private String color;
    private int price;

    void setName(String name) {
        this.name = name;
    }

    String getName() {
        return this.name;
    }

    void setColor(String color) {
        this.color = color;
    }

    String getColor() {
        return this.color;
    }

    void setPrice(int price) {
        this.price = price;
    }

    int getPrice() {
        return this.price;
    }

}